import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createReadStream } from 'node:fs';
import { Readable } from 'node:stream';
import { mkdtemp, readdir, rm, stat } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';

const run = promisify(execFile);
const workspace = path.resolve(process.cwd());
const temporary = await mkdtemp(path.join(workspace, '.chroma-smoke-'));
process.env.CHROMA_PROJECT_DIR = path.join(temporary, 'projects');
const { createProject, deleteProject, deleteTemporaryProject, exportProject, generateProject, listProjects, readProfile, readProject, readProjectSource, readProjectSourceInfo, replaceProjectSource, saveProfile, updateProject, uploadProjectSource } = await import('../chroma/frameProjects.mjs');
const { filterFor, parseConfig } = await import('../chroma/config.mjs');
const input = path.join(temporary, 'sample.mp4');
const output = await mkdtemp(path.join(tmpdir(), 'codex-chroma-output-'));
try {
  await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=c=green:s=64x32:r=5:d=2', '-vf', 'drawbox=x=10:y=7:w=12:h=12:color=red:t=fill', '-pix_fmt', 'yuv420p', input]);
  const project = await createProject('sample.mp4', { fps: 5, sourceFps: 5, startFrame: 1, endFrame: 10 });
  await uploadProjectSource(project.id, createReadStream(input));
  let ready;
  for (let attempt = 0; attempt < 100; attempt++) {
    ready = await readProject(project.id);
    if (ready.status === 'ready' || ready.status === 'error') break;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert.equal(ready.status, 'ready', ready.error);
  assert.equal(ready.frameCount, 10);
  assert.equal((await readProjectSource(project.id)).size, (await stat(input)).size);
  const slots = [...ready.slots];
  slots[1] = { frame: null };
  slots[2] = { frame: 1 };
  await updateProject(project.id, slots);
  assert.equal((await readProject(project.id)).slots[1].frame, null);
  const png = await exportProject(project.id, 'png', 1, output);
  assert.equal((await readdir(png.path)).filter(name => name.endsWith('.png')).length, 10);
  const emptyRaw = (await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-v', 'error', '-i', path.join(png.path, '000002.png'), '-f', 'rawvideo', '-pix_fmt', 'rgba', 'pipe:1'], { encoding: 'buffer' })).stdout;
  assert.equal([...emptyRaw].filter((_, index) => index % 4 === 3).every(alpha => alpha === 0), true, 'Cleared frame must have transparent alpha.');
  const originalPng = await exportProject(project.id, 'png', 1, output, 'original');
  assert.equal((await readdir(originalPng.path)).filter(name => name.endsWith('.png')).length, 10);
  const originalSecond = (await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-v', 'error', '-i', path.join(originalPng.path, '000002.png'), '-f', 'rawvideo', '-pix_fmt', 'rgba', 'pipe:1'], { encoding: 'buffer' })).stdout;
  assert.equal([...originalSecond].filter((_, index) => index % 4 === 3).some(alpha => alpha > 0), true, 'Original order must retain the source frame after an edited slot is cleared.');
  const atlas = await exportProject(project.id, 'atlas', 2, output);
  assert.equal(atlas.columns, 5);
  const metadata = JSON.parse((await run(process.env.FFPROBE_PATH || 'ffprobe', ['-v', 'error', '-show_entries', 'stream=width,height', '-of', 'json', atlas.path])).stdout);
  assert.equal(metadata.streams[0].width, 320);
  assert.equal(metadata.streams[0].height, 64);
  const paddedAtlas = await exportProject(project.id, 'atlas', 3, output);
  assert.equal(paddedAtlas.columns, 4);
  const paddedRaw = (await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-v', 'error', '-i', paddedAtlas.path, '-f', 'rawvideo', '-pix_fmt', 'rgba', 'pipe:1'], { encoding: 'buffer' })).stdout;
  const paddedPixel = ((2 * 32 + 16) * 256 + (3 * 64 + 16)) * 4;
  assert.equal(paddedRaw[paddedPixel + 3], 0, 'Unused atlas cell must stay transparent.');
  const webp = await exportProject(project.id, 'webp', 1, output);
  const packets = JSON.parse((await run(process.env.FFPROBE_PATH || 'ffprobe', ['-v', 'error', '-show_packets', '-show_entries', 'packet=duration_time', '-of', 'json', webp.path])).stdout);
  const duration = packets.packets.reduce((sum, packet) => sum + Number(packet.duration_time), 0);
  assert.ok(Math.abs(duration - 2) < 0.01, `Expected two seconds of playback, got ${duration}.`);
  const temporaryProject = await createProject('temporary.mp4', { fps: 5, sourceFps: 5, startFrame: 1, endFrame: 10 }, '', true);
  assert.equal((await listProjects()).some(item => item.id === temporaryProject.id), false);
  await deleteTemporaryProject(temporaryProject.id);
  assert.equal(await stat(path.join(process.env.CHROMA_PROJECT_DIR, temporaryProject.id)).catch(() => null), null);
  const uploaded = await createProject('uploaded.mp4', { fps: 5, sourceFps: 5, startFrame: 1, endFrame: 10 }, '', false, true);
  await uploadProjectSource(uploaded.id, createReadStream(input));
  assert.equal((await readProject(uploaded.id)).status, 'source-ready');
  assert.equal((await readProjectSourceInfo(uploaded.id)).fps, 5);
  assert.equal((await listProjects()).some(item => item.id === uploaded.id), true);
  const savedProfile = { profile: { settings: { color: '#00FF00', similarity: 0.27 }, sourceFps: 5, frame: 3, outputDirectory: output }, range: { start: 3, end: 8 } };
  await saveProfile(uploaded.id, savedProfile);
  assert.deepEqual(await readProfile(uploaded.id), savedProfile);
  await generateProject(uploaded.id, { fps: 5, sourceFps: 5, startFrame: 1, endFrame: 10 });
  let generated;
  for (let attempt = 0; attempt < 100; attempt++) {
    generated = await readProject(uploaded.id);
    if (generated.status === 'ready' || generated.status === 'error') break;
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  assert.equal(generated.status, 'ready', generated.error);
  assert.equal(generated.id, uploaded.id, 'Generating frames must not create a separate project entry.');
  assert.deepEqual(await readProfile(uploaded.id), savedProfile);
  assert.equal((await listProjects()).filter(item => [project.id, uploaded.id].includes(item.id)).length, 2);
  assert.equal((await readProject(project.id)).slots[1].frame, null, 'Generating another file must not alter the first file’s edited slots.');
  await assert.rejects(replaceProjectSource(uploaded.id, Readable.from(Buffer.from('not an MP4')), 'invalid.mp4'));
  assert.equal((await readProject(uploaded.id)).status, 'ready', 'Invalid replacements must leave generated frames intact.');
  assert.equal((await readProjectSource(uploaded.id)).size, (await stat(input)).size);
  const replacement = path.join(temporary, 'replacement.mp4');
  await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'color=c=magenta:s=32x32:r=5:d=1', '-pix_fmt', 'yuv420p', replacement]);
  const replaced = await replaceProjectSource(uploaded.id, createReadStream(replacement), 'replacement.mp4');
  assert.equal(replaced.status, 'source-ready');
  assert.equal(replaced.name, 'replacement.mp4');
  assert.equal(replaced.frameCount, 0);
  assert.deepEqual(replaced.slots, []);
  assert.deepEqual(await readdir(path.join(process.env.CHROMA_PROJECT_DIR, uploaded.id, 'frames')), []);
  assert.equal((await readProjectSource(uploaded.id)).size, (await stat(replacement)).size);
  assert.deepEqual(await readProfile(uploaded.id), savedProfile, 'Replacing the source keeps the file settings.');
  const differentRate = path.join(temporary, 'source-24fps.mp4');
  await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-hide_banner', '-loglevel', 'error', '-f', 'lavfi', '-i', 'testsrc2=s=64x32:r=24:d=10', '-pix_fmt', 'yuv420p', differentRate]);
  const timingConfig = parseConfig({ color: '#FF00DD', sourceFps: 30, fps: 30, startFrame: 134, endFrame: 163 });
  const timingFilter = filterFor(timingConfig, { width: 64, height: 32 }).replace(/trim=[^,]+/, match => `${match},showinfo`);
  const timingProbe = await run(process.env.FFMPEG_PATH || 'ffmpeg', ['-hide_banner', '-loglevel', 'info', '-i', differentRate, '-an', '-vf', timingFilter, '-frames:v', '1', '-f', 'null', '-']);
  const firstSourceTime = Number(timingProbe.stderr.match(/showinfo[^\n]*pts_time:\s*([\d.]+)/)?.[1]);
  assert.ok(Number.isFinite(firstSourceTime) && Math.abs(firstSourceTime - 133 / 30) < 1 / 24, `Expected source time near 4.43s, got ${firstSourceTime}s.`);
  await deleteProject(uploaded.id, true);
  assert.equal((await listProjects()).some(item => item.id === uploaded.id), false);
  console.log('Frame project smoke test passed: persisted profile, frame timing across source rates, source replacement and rollback, original/edited exports, PNG, atlas, WebP, cleanup.');
} finally {
  if (temporary.startsWith(`${workspace}${path.sep}`)) await rm(temporary, { recursive: true, force: true });
  if (path.resolve(output).toLowerCase().startsWith(`${path.resolve(tmpdir()).toLowerCase()}${path.sep}`)) await rm(output, { recursive: true, force: true });
}
